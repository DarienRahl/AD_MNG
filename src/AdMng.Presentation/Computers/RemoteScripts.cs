using System.Globalization;
using System.Text;
using AdMng.Core.Batch;
using AdMng.Core.Computers.Remote;

namespace AdMng.Presentation.Computers;

/// <summary>
/// The PowerShell equivalents of remote actions (K1 design note 4.7): a CIM session with Kerberos and the commands the
/// action ran. Never a credential – <c>Get-Credential</c> asks for it; every literal through
/// <see cref="PowerShellExporter.Quote"/>.
/// </summary>
public static class RemoteScripts
{
    private const string NewLine = "\r\n";

    /// <summary>The script of one action: session, commands, Remove-CimSession.</summary>
    /// <param name="host">The computer's DNS name.</param>
    /// <param name="options">Transport options.</param>
    /// <param name="explicitCredential">The window has a typed credential (else the Windows account of the process).</param>
    /// <param name="commands">The commands, using <c>$s</c>.</param>
    public static string Build(string host, RemoteOptions options, bool explicitCredential, params string[] commands)
    {
        ArgumentNullException.ThrowIfNull(options);
        var session = new StringBuilder("$s = New-CimSession -ComputerName ").Append(PowerShellExporter.Quote(host));
        if (explicitCredential)
        {
            session.Append(" -Credential (Get-Credential)");
        }

        session.Append(" -Authentication Kerberos");
        if (options.Port is { } port)
        {
            session.Append(" -Port ").Append(port.ToString(CultureInfo.InvariantCulture));
        }

        if (options.UseHttps)
        {
            session.Append(" -SessionOption (New-CimSessionOption -UseSsl)");
        }

        var sb = new StringBuilder("# Generated by AD Manager - review before running.").Append(NewLine)
            .Append(session).Append(NewLine);
        foreach (var command in commands)
        {
            sb.Append(command).Append(NewLine);
        }

        return sb.Append("Remove-CimSession $s").Append(NewLine).ToString();
    }

    public const string OperatingSystem =
        "Get-CimInstance -CimSession $s -ClassName Win32_OperatingSystem | Select-Object Caption, Version, BuildNumber, LastBootUpTime";

    public const string LoggedOnUsers =
        "Get-CimInstance -CimSession $s -ClassName Win32_Process -Filter \"Name='explorer.exe'\" | Invoke-CimMethod -MethodName GetOwner";

    public const string Services =
        "Get-CimInstance -CimSession $s -ClassName Win32_Service | Select-Object Name, DisplayName, State, StartMode, DelayedAutoStart, StartName";

    public const string RefreshPolicy =
        "Invoke-CimMethod -CimSession $s -ClassName Win32_Process -MethodName Create -Arguments @{ CommandLine = 'gpupdate.exe /target:computer /force /wait:0' }";

    public const string AbortRestart =
        "Invoke-CimMethod -CimSession $s -ClassName Win32_Process -MethodName Create -Arguments @{ CommandLine = 'shutdown.exe /a' }";

    /// <summary>Win32ShutdownTracker with the delay, the message, planned/other and reboot (+ force).</summary>
    public static string Restart(TimeSpan delay, string message, bool force) => string.Create(
        CultureInfo.InvariantCulture,
        $"Get-CimInstance -CimSession $s -ClassName Win32_OperatingSystem | Invoke-CimMethod -MethodName Win32ShutdownTracker -Arguments @{{ Timeout = [uint32]{(int)delay.TotalSeconds}; Comment = {PowerShellExporter.Quote(message)}; ReasonCode = [uint32]2147483648; Flags = {(force ? 6 : 2)} }}");
}
