using System.Globalization;
using System.Text;
using AdMng.Core.ActiveDirectory;
using AdMng.Core.Ldap;

namespace AdMng.Core.Batch;

/// <summary>
/// Default <see cref="IPowerShellExporter"/>: produces a reviewable script for the ActiveDirectory module.
/// </summary>
/// <remarks>
/// All literals are single-quoted (embedded quotes - including the typographic quotes PowerShell treats as quotes -
/// are doubled). Each object gets a <c>$dn</c> variable that follows renames and moves. Passwords are never written
/// to the script: every reset prompts with <c>Read-Host -AsSecureString</c>. Objects with errors are listed as
/// comments only. Lines end with CRLF.
/// </remarks>
public sealed class PowerShellExporter : IPowerShellExporter
{
    private const string NewLine = "\r\n";

    /// <summary>Attributes emitted as PowerShell numbers instead of strings.</summary>
    private static readonly HashSet<string> NumericAttributes = new(StringComparer.OrdinalIgnoreCase)
    {
        Attr.UserAccountControl, Attr.PwdLastSet, Attr.LockoutTime, Attr.AccountExpires, Attr.GroupType, Attr.PrimaryGroupId,
        Attr.CountryCode, Attr.SupportedEncryptionTypes,
    };

    /// <inheritdoc />
    public string Export(ChangePlan plan, string? server)
    {
        ArgumentNullException.ThrowIfNull(plan);
        server ??= plan.Server;
        var sb = new StringBuilder();
        WriteHeader(sb, plan, server);
        var serverArgument = string.IsNullOrEmpty(server) ? string.Empty : " -Server $server";

        var number = 0;
        foreach (var objectPlan in plan.Objects)
        {
            number++;
            Line(sb);
            Line(sb, $"# [{number}] {Comment(objectPlan.DisplayName)} - {Comment(objectPlan.DistinguishedName)}");
            WriteIssues(sb, objectPlan.Issues.Concat(objectPlan.Changes.SelectMany(c => c.Issues)));
            if (objectPlan.HasErrors)
            {
                Line(sb, "# SKIPPED: the object has validation errors.");
                continue;
            }

            if (objectPlan.IsNoOp)
            {
                Line(sb, "# No changes.");
                continue;
            }

            Line(sb, $"$dn = {Quote(objectPlan.DistinguishedName)}");
            foreach (var change in objectPlan.Changes)
            {
                WriteChange(sb, objectPlan, change, serverArgument);
            }
        }

        return sb.ToString();
    }

    /// <summary>Quotes a value as a PowerShell single-quoted string literal.</summary>
    public static string Quote(string value)
    {
        ArgumentNullException.ThrowIfNull(value);
        var sb = new StringBuilder(value.Length + 2);
        sb.Append('\'');
        foreach (var c in value)
        {
            // PowerShell treats ' and the typographic single quotes as string delimiters.
            if (c is '\'' or '‘' or '’' or '‚' or '‛')
            {
                sb.Append(c);
            }

            sb.Append(c);
        }

        sb.Append('\'');
        return sb.ToString();
    }

    private static void WriteHeader(StringBuilder sb, ChangePlan plan, string? server)
    {
        Line(sb, "# Generated by AD Manager - review before running.");
        if (!string.IsNullOrEmpty(plan.Title))
        {
            Line(sb, $"# Title: {Comment(plan.Title)}");
        }

        Line(sb, $"# Plan created: {plan.CreatedAt.ToUniversalTime().ToString("yyyy-MM-dd HH:mm:ss", CultureInfo.InvariantCulture)} UTC");
        Line(sb, $"# Domain controller: {Comment(server ?? "(not set)")}");
        Line(sb, string.Create(CultureInfo.InvariantCulture,
            $"# Objects: {plan.Objects.Count} total, {plan.ExecutableCount} with changes, {plan.ErrorCount} with errors (skipped), {plan.NoOpCount} without changes"));
        if (plan.ContainsPasswords)
        {
            Line(sb, "# Passwords are not included; the script prompts for each new password.");
        }

        Line(sb, "#Requires -Modules ActiveDirectory");
        Line(sb, "$ErrorActionPreference = 'Stop'");
        if (!string.IsNullOrEmpty(server))
        {
            Line(sb, $"$server = {Quote(server)}");
        }
    }

    private static void WriteIssues(StringBuilder sb, IEnumerable<ValidationIssue> issues)
    {
        foreach (var issue in issues)
        {
            var attribute = issue.Attribute is null ? string.Empty : $" ({issue.Attribute})";
            Line(sb, $"# {issue.Severity} [{issue.Code}]{Comment(attribute)}: {Comment(issue.Message)}");
        }
    }

    private static void WriteChange(StringBuilder sb, ObjectPlan objectPlan, PlannedChange change, string server)
    {
        switch (change.Action)
        {
            case ChangeAction.Modify:
                WriteModify(sb, change, server);
                break;
            case ChangeAction.ResetPassword:
                Line(sb, $"# New password for {Comment(objectPlan.DisplayName)}");
                Line(sb, $"$password = Read-Host -AsSecureString -Prompt {Quote("New password for " + objectPlan.DisplayName)}");
                Line(sb, $"Set-ADAccountPassword -Identity $dn -Reset -NewPassword $password{server}");
                Line(sb, "Remove-Variable password");
                break;
            case ChangeAction.AddMember:
                Line(sb, $"Set-ADGroup -Identity {Quote(change.TargetDn ?? string.Empty)} -Add @{{member=$dn}}{server}");
                break;
            case ChangeAction.RemoveMember:
                Line(sb, $"Set-ADGroup -Identity {Quote(change.TargetDn ?? string.Empty)} -Remove @{{member=$dn}}{server}");
                break;
            case ChangeAction.Rename:
                var newName = DistinguishedName.TryParse(change.TargetDn, out var rdn) && !rdn.IsRoot ? rdn.Name : change.TargetDn ?? string.Empty;
                Line(sb, $"$dn = (Rename-ADObject -Identity $dn -NewName {Quote(newName)}{server} -PassThru).DistinguishedName");
                break;
            case ChangeAction.Move:
                Line(sb, $"$dn = (Move-ADObject -Identity $dn -TargetPath {Quote(change.TargetDn ?? string.Empty)}{server} -PassThru).DistinguishedName");
                break;
            case ChangeAction.Delete:
                Line(sb, $"Remove-ADObject -Identity $dn{(change.DeleteSubtree ? " -Recursive" : string.Empty)}{server} -Confirm:$false");
                break;
            case ChangeAction.Create:
                WriteCreate(sb, objectPlan, change, server);
                break;
        }
    }

    private static void WriteModify(StringBuilder sb, PlannedChange change, string server)
    {
        var replace = new List<string>();
        var add = new List<string>();
        var remove = new List<string>();
        var clear = new List<string>();
        var unlock = false;
        foreach (var attribute in change.Attributes)
        {
            if (string.Equals(attribute.Attribute, Attr.LockoutTime, StringComparison.OrdinalIgnoreCase)
                && attribute.Kind == AttributeChangeKind.Replace && attribute.NewValues is ["0"])
            {
                unlock = true;
                continue;
            }

            switch (attribute.Kind)
            {
                case AttributeChangeKind.Replace:
                    replace.Add(HashEntry(attribute.Attribute, attribute.NewValues));
                    break;
                case AttributeChangeKind.Clear:
                    clear.Add(Key(attribute.Attribute));
                    break;
                case AttributeChangeKind.AddValues:
                    add.Add(HashEntry(attribute.Attribute, attribute.NewValues));
                    break;
                case AttributeChangeKind.RemoveValues:
                    remove.Add(HashEntry(attribute.Attribute, attribute.NewValues));
                    break;
            }
        }

        if (replace.Count + add.Count + remove.Count + clear.Count > 0)
        {
            var command = new StringBuilder("Set-ADObject -Identity $dn");
            if (replace.Count > 0)
            {
                command.Append(" -Replace @{").Append(string.Join("; ", replace)).Append('}');
            }

            if (clear.Count > 0)
            {
                command.Append(" -Clear ").Append(string.Join(",", clear));
            }

            if (add.Count > 0)
            {
                command.Append(" -Add @{").Append(string.Join("; ", add)).Append('}');
            }

            if (remove.Count > 0)
            {
                command.Append(" -Remove @{").Append(string.Join("; ", remove)).Append('}');
            }

            Line(sb, command.Append(server).ToString());
        }

        if (unlock)
        {
            Line(sb, $"Unlock-ADAccount -Identity $dn{server}");
        }
    }

    private static void WriteCreate(StringBuilder sb, ObjectPlan objectPlan, PlannedChange change, string server)
    {
        if (!DistinguishedName.TryParse(objectPlan.DistinguishedName, out var dn) || dn.IsRoot || dn.Parent is not { } parent)
        {
            Line(sb, "# Cannot create the object: its DN is invalid.");
            return;
        }

        var type = objectPlan.ObjectClasses.Count > 0 ? objectPlan.ObjectClasses[^1] : "user";
        var otherAttributes = change.Attributes
            .Where(a => a.NewValues.Count > 0
                && !string.Equals(a.Attribute, Attr.ObjectClass, StringComparison.OrdinalIgnoreCase)
                && !string.Equals(a.Attribute, dn.Leaf.Type, StringComparison.OrdinalIgnoreCase))
            .Select(a => HashEntry(a.Attribute, a.NewValues))
            .ToList();
        var command = new StringBuilder($"New-ADObject -Name {Quote(dn.Name)} -Type {Quote(type)} -Path {Quote(parent.ToString())}");
        if (otherAttributes.Count > 0)
        {
            command.Append(" -OtherAttributes @{").Append(string.Join("; ", otherAttributes)).Append('}');
        }

        Line(sb, command.Append(server).ToString());
    }

    private static string HashEntry(string attribute, IReadOnlyList<string> values)
    {
        var literals = values.Select(v => Literal(attribute, v)).ToList();
        var value = literals.Count == 1 ? literals[0] : $"@({string.Join(",", literals)})";
        return $"{Key(attribute)}={value}";
    }

    private static string Literal(string attribute, string value)
    {
        if (NumericAttributes.Contains(attribute)
            && long.TryParse(value, NumberStyles.AllowLeadingSign, CultureInfo.InvariantCulture, out var number))
        {
            return number.ToString(CultureInfo.InvariantCulture);
        }

        return value switch
        {
            "TRUE" => "$true",
            "FALSE" => "$false",
            _ => Quote(value),
        };
    }

    /// <summary>Hashtable key / -Clear name: bare when it is a simple identifier, quoted otherwise (e.g. msDS-...).</summary>
    private static string Key(string attribute) => attribute.All(char.IsAsciiLetterOrDigit) ? attribute : Quote(attribute);

    /// <summary>Makes text safe for a single-line comment.</summary>
    private static string Comment(string text) => text.Replace('\r', ' ').Replace('\n', ' ');

    private static void Line(StringBuilder sb, string text = "") => sb.Append(text).Append(NewLine);
}
