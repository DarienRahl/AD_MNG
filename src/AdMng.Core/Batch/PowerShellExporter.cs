using System.Globalization;
using System.Text;
using AdMng.Core.ActiveDirectory;
using AdMng.Core.Ldap;
using AdMng.Core.Schema;

namespace AdMng.Core.Batch;

/// <summary>
/// Default <see cref="IPowerShellExporter"/>: produces a reviewable script for the ActiveDirectory module.
/// </summary>
/// <remarks>
/// All literals are single-quoted (embedded quotes - including the typographic quotes PowerShell treats as quotes -
/// are doubled). Each object gets a <c>$dn</c> variable that follows renames and moves. Passwords are never written
/// to the script: every reset prompts with <c>Read-Host -AsSecureString</c>, and so does every value of a secret attribute
/// (<see cref="SecretAttributes"/>: LAPS, BitLocker... and the schema's confidential attributes) - the command then uses
/// the variable the value was read into, which is removed afterwards. Objects with errors are listed as comments only.
/// Lines end with CRLF.
/// </remarks>
public sealed class PowerShellExporter : IPowerShellExporter
{
    private const string NewLine = "\r\n";

    /// <summary>Attributes emitted as PowerShell numbers instead of strings.</summary>
    private static readonly HashSet<string> NumericAttributes = new(StringComparer.OrdinalIgnoreCase)
    {
        Attr.UserAccountControl, Attr.PwdLastSet, Attr.LockoutTime, Attr.AccountExpires, Attr.GroupType, Attr.PrimaryGroupId,
        Attr.CountryCode, Attr.SupportedEncryptionTypes,
    };

    /// <inheritdoc />
    public string Export(ChangePlan plan, string? server, ISchemaCatalog? schema = null)
    {
        ArgumentNullException.ThrowIfNull(plan);
        server ??= plan.Server;
        var sb = new StringBuilder();
        WriteHeader(sb, plan, server, schema);
        var serverArgument = string.IsNullOrEmpty(server) ? string.Empty : " -Server $server";

        var number = 0;
        foreach (var objectPlan in plan.Objects)
        {
            number++;
            Line(sb);
            Line(sb, $"# [{number}] {Comment(objectPlan.DisplayName)} - {Comment(objectPlan.DistinguishedName)}");
            WriteIssues(sb, objectPlan.Issues.Concat(objectPlan.Changes.SelectMany(c => c.Issues)));
            if (objectPlan.HasErrors)
            {
                Line(sb, "# SKIPPED: the object has validation errors.");
                continue;
            }

            if (objectPlan.IsNoOp)
            {
                Line(sb, "# No changes.");
                continue;
            }

            Line(sb, $"$dn = {Quote(objectPlan.DistinguishedName)}");
            foreach (var change in objectPlan.Changes)
            {
                WriteChange(sb, objectPlan, change, serverArgument, schema);
            }
        }

        return sb.ToString();
    }

    /// <summary>Quotes a value as a PowerShell single-quoted string literal.</summary>
    public static string Quote(string value)
    {
        ArgumentNullException.ThrowIfNull(value);
        var sb = new StringBuilder(value.Length + 2);
        sb.Append('\'');
        foreach (var c in value)
        {
            // PowerShell treats ' and the typographic single quotes as string delimiters.
            if (c is '\'' or '‘' or '’' or '‚' or '‛')
            {
                sb.Append(c);
            }

            sb.Append(c);
        }

        sb.Append('\'');
        return sb.ToString();
    }

    private static void WriteHeader(StringBuilder sb, ChangePlan plan, string? server, ISchemaCatalog? schema)
    {
        Line(sb, "# Generated by AD Manager - review before running.");
        if (!string.IsNullOrEmpty(plan.Title))
        {
            Line(sb, $"# Title: {Comment(plan.Title)}");
        }

        Line(sb, $"# Plan created: {plan.CreatedAt.ToUniversalTime().ToString("yyyy-MM-dd HH:mm:ss", CultureInfo.InvariantCulture)} UTC");
        Line(sb, $"# Domain controller: {Comment(server ?? "(not set)")}");
        Line(sb, string.Create(CultureInfo.InvariantCulture,
            $"# Objects: {plan.Objects.Count} total, {plan.ExecutableCount} with changes, {plan.ErrorCount} with errors (skipped), {plan.NoOpCount} without changes"));
        if (plan.ContainsPasswords)
        {
            Line(sb, "# Passwords are not included; the script prompts for each new password.");
        }

        if (plan.Objects.Any(o => !o.HasErrors && o.Changes.Any(c => c.Action is ChangeAction.Modify or ChangeAction.Create
                && c.Attributes.Any(a => a.NewValues.Count > 0 && SecretAttributes.IsSecret(a.Attribute, schema)))))
        {
            Line(sb, "# Values of secret attributes are not included; the script prompts for each of them.");
        }

        Line(sb, "#Requires -Modules ActiveDirectory");
        Line(sb, "$ErrorActionPreference = 'Stop'");
        if (!string.IsNullOrEmpty(server))
        {
            Line(sb, $"$server = {Quote(server)}");
        }
    }

    private static void WriteIssues(StringBuilder sb, IEnumerable<ValidationIssue> issues)
    {
        foreach (var issue in issues)
        {
            var attribute = issue.Attribute is null ? string.Empty : $" ({issue.Attribute})";
            Line(sb, $"# {issue.Severity} [{issue.Code}]{Comment(attribute)}: {Comment(issue.Message)}");
        }
    }

    private static void WriteChange(StringBuilder sb, ObjectPlan objectPlan, PlannedChange change, string server, ISchemaCatalog? schema)
    {
        switch (change.Action)
        {
            case ChangeAction.Modify:
                WriteModify(sb, objectPlan, change, server, schema);
                break;
            case ChangeAction.ResetPassword:
                Line(sb, $"# New password for {Comment(objectPlan.DisplayName)}");
                Line(sb, $"$password = Read-Host -AsSecureString -Prompt {Quote("New password for " + objectPlan.DisplayName)}");
                Line(sb, $"Set-ADAccountPassword -Identity $dn -Reset -NewPassword $password{server}");
                Line(sb, "Remove-Variable password");
                break;
            case ChangeAction.AddMember:
                Line(sb, $"Set-ADGroup -Identity {Quote(change.TargetDn ?? string.Empty)} -Add @{{member=$dn}}{server}");
                break;
            case ChangeAction.RemoveMember:
                Line(sb, $"Set-ADGroup -Identity {Quote(change.TargetDn ?? string.Empty)} -Remove @{{member=$dn}}{server}");
                break;
            case ChangeAction.Rename:
                var newName = DistinguishedName.TryParse(change.TargetDn, out var rdn) && !rdn.IsRoot ? rdn.Name : change.TargetDn ?? string.Empty;
                Line(sb, $"$dn = (Rename-ADObject -Identity $dn -NewName {Quote(newName)}{server} -PassThru).DistinguishedName");
                break;
            case ChangeAction.Move:
                Line(sb, $"$dn = (Move-ADObject -Identity $dn -TargetPath {Quote(change.TargetDn ?? string.Empty)}{server} -PassThru).DistinguishedName");
                break;
            case ChangeAction.Delete:
                Line(sb, $"Remove-ADObject -Identity $dn{(change.DeleteSubtree ? " -Recursive" : string.Empty)}{server} -Confirm:$false");
                break;
            case ChangeAction.Create:
                WriteCreate(sb, objectPlan, change, server, schema);
                break;
            case ChangeAction.Restore:
                WriteRestore(sb, objectPlan, change, server);
                break;
            case ChangeAction.ModifySecurity:
                WriteModifySecurity(sb, change, server);
                break;
        }
    }

    /// <summary>
    /// Restore-ADObject with the new name and parent. The deleted object is identified by its objectGUID when the plan knows
    /// it; otherwise it is read by its DN in CN=Deleted Objects with Get-ADObject -IncludeDeletedObjects and piped on.
    /// </summary>
    private static void WriteRestore(StringBuilder sb, ObjectPlan objectPlan, PlannedChange change, string server)
    {
        if (!DistinguishedName.TryParse(change.TargetDn, out var target) || target.IsRoot || target.Parent is not { IsRoot: false } parent)
        {
            Line(sb, "# Cannot restore the object: its target DN is invalid.");
            return;
        }

        var arguments = $"-NewName {Quote(target.Name)} -TargetPath {Quote(parent.ToString())}{server}";
        Line(sb, objectPlan.ObjectGuid is { } guid
            ? $"Restore-ADObject -Identity {Quote(guid.ToString("D"))} {arguments}"
            : $"Get-ADObject -Identity $dn -IncludeDeletedObjects{server} | Restore-ADObject {arguments}");
        Line(sb, $"$dn = {Quote(target.ToString())}");
    }

    /// <summary>
    /// A DACL delta through the AD: drive of the ActiveDirectory module: Get-Acl, one ActiveDirectoryAccessRule per ACE
    /// (AddAccessRule / RemoveAccessRuleSpecific), Set-Acl. With a pinned DC the drive <c>ADMNG:</c> is created on it
    /// (New-PSDrive -Server), so the read and the write go to the plan's DC.
    /// </summary>
    private static void WriteModifySecurity(StringBuilder sb, PlannedChange change, string server)
    {
        if (change.Acl is not { IsEmpty: false } acl)
        {
            Line(sb, "# No permission change.");
            return;
        }

        var drive = "AD";
        if (!string.IsNullOrEmpty(server))
        {
            drive = "ADMNG";
            Line(sb, "if (-not (Get-PSDrive -Name ADMNG -ErrorAction SilentlyContinue)) { New-PSDrive -Name ADMNG -PSProvider ActiveDirectory -Root '//RootDSE/'" + server + " | Out-Null }");
        }

        Line(sb, $"$acl = Get-Acl -LiteralPath \"{drive}:$dn\"");
        foreach (var ace in acl.Removed)
        {
            TrusteeComment(sb, "-", ace);
            Line(sb, $"$acl.RemoveAccessRuleSpecific({AccessRule(ace)})");
        }

        foreach (var ace in acl.Added)
        {
            TrusteeComment(sb, "+", ace);
            Line(sb, $"$acl.AddAccessRule({AccessRule(ace)})");
        }

        Line(sb, $"Set-Acl -LiteralPath \"{drive}:$dn\" -AclObject $acl");
    }

    private static void TrusteeComment(StringBuilder sb, string sign, Security.AceSpec ace)
    {
        var name = string.IsNullOrWhiteSpace(ace.TrusteeName) ? ace.TrusteeSid : ace.TrusteeName;
        Line(sb, $"# {sign} {Comment(name)}: {Comment(ace.Describe())}");
    }

    /// <summary>
    /// <c>[System.DirectoryServices.ActiveDirectoryAccessRule]::new(sid, rights, type, objectType, inheritance,
    /// inheritedObjectType)</c> of one ACE.
    /// </summary>
    private static string AccessRule(Security.AceSpec ace)
    {
        var rights = RightsLiteral(ace.Mask);
        var type = ace.Qualifier == Security.AceQualifier.Allow ? "Allow" : "Deny";
        var objectType = (ace.ObjectType ?? Guid.Empty).ToString("D");
        var inherited = (ace.InheritedObjectType ?? Guid.Empty).ToString("D");
        return "[System.DirectoryServices.ActiveDirectoryAccessRule]::new("
            + $"[System.Security.Principal.SecurityIdentifier]{Quote(ace.TrusteeSid)}, "
            + $"[System.DirectoryServices.ActiveDirectoryRights]{rights}, "
            + $"[System.Security.AccessControl.AccessControlType]'{type}', "
            + $"[guid]'{objectType}', "
            + $"[System.DirectoryServices.ActiveDirectorySecurityInheritance]'{Inheritance(ace.Flags)}', "
            + $"[guid]'{inherited}')";
    }

    /// <summary>The ActiveDirectoryRights of a mask: flag names when every bit has one, the number otherwise.</summary>
    private static string RightsLiteral(int mask)
    {
        (int Bit, string Name)[] names =
        [
            (0x1, "CreateChild"), (0x2, "DeleteChild"), (0x4, "ListChildren"), (0x8, "Self"), (0x10, "ReadProperty"),
            (0x20, "WriteProperty"), (0x40, "DeleteTree"), (0x80, "ListObject"), (0x100, "ExtendedRight"), (0x10000, "Delete"),
            (0x20000, "ReadControl"), (0x40000, "WriteDacl"), (0x80000, "WriteOwner"),
        ];
        if (mask == 0xF01FF)
        {
            return "'GenericAll'";
        }

        var known = names.Where(n => (mask & n.Bit) != 0).ToList();
        return known.Sum(n => n.Bit) == mask
            ? $"'{string.Join(", ", known.Select(n => n.Name))}'"
            : mask.ToString(CultureInfo.InvariantCulture);
    }

    /// <summary>ActiveDirectorySecurityInheritance of the ACE flags (container inherit, inherit only, no propagate).</summary>
    private static string Inheritance(byte flags)
    {
        var container = (flags & Security.SecurityDescriptorAce.ContainerInheritFlag) != 0;
        var inheritOnly = (flags & Security.SecurityDescriptorAce.InheritOnlyFlag) != 0;
        var noPropagate = (flags & Security.SecurityDescriptorAce.NoPropagateInheritFlag) != 0;
        return (container, inheritOnly, noPropagate) switch
        {
            (false, _, _) => "None",
            (true, false, false) => "All",
            (true, true, false) => "Descendents",
            (true, false, true) => "SelfAndChildren",
            _ => "Children",
        };
    }

    private static void WriteModify(StringBuilder sb, ObjectPlan objectPlan, PlannedChange change, string server, ISchemaCatalog? schema)
    {
        var secrets = new List<string>();
        var replace = new List<string>();
        var add = new List<string>();
        var remove = new List<string>();
        var clear = new List<string>();
        var unlock = false;
        foreach (var attribute in change.Attributes)
        {
            if (string.Equals(attribute.Attribute, Attr.LockoutTime, StringComparison.OrdinalIgnoreCase)
                && attribute.Kind == AttributeChangeKind.Replace && attribute.NewValues is ["0"])
            {
                unlock = true;
                continue;
            }

            switch (attribute.Kind)
            {
                case AttributeChangeKind.Replace:
                    replace.Add(Entry(sb, objectPlan, attribute.Attribute, attribute.NewValues, schema, secrets));
                    break;
                case AttributeChangeKind.Clear:
                    clear.Add(Key(attribute.Attribute));
                    break;
                case AttributeChangeKind.AddValues:
                    add.Add(Entry(sb, objectPlan, attribute.Attribute, attribute.NewValues, schema, secrets));
                    break;
                case AttributeChangeKind.RemoveValues:
                    remove.Add(Entry(sb, objectPlan, attribute.Attribute, attribute.NewValues, schema, secrets));
                    break;
            }
        }

        if (replace.Count + add.Count + remove.Count + clear.Count > 0)
        {
            var command = new StringBuilder("Set-ADObject -Identity $dn");
            if (replace.Count > 0)
            {
                command.Append(" -Replace @{").Append(string.Join("; ", replace)).Append('}');
            }

            if (clear.Count > 0)
            {
                command.Append(" -Clear ").Append(string.Join(",", clear));
            }

            if (add.Count > 0)
            {
                command.Append(" -Add @{").Append(string.Join("; ", add)).Append('}');
            }

            if (remove.Count > 0)
            {
                command.Append(" -Remove @{").Append(string.Join("; ", remove)).Append('}');
            }

            Line(sb, command.Append(server).ToString());
        }

        RemoveSecrets(sb, secrets);
        if (unlock)
        {
            Line(sb, $"Unlock-ADAccount -Identity $dn{server}");
        }
    }

    private static void WriteCreate(StringBuilder sb, ObjectPlan objectPlan, PlannedChange change, string server, ISchemaCatalog? schema)
    {
        if (!DistinguishedName.TryParse(objectPlan.DistinguishedName, out var dn) || dn.IsRoot || dn.Parent is not { } parent)
        {
            Line(sb, "# Cannot create the object: its DN is invalid.");
            return;
        }

        var type = objectPlan.ObjectClasses.Count > 0 ? objectPlan.ObjectClasses[^1] : "user";
        var secrets = new List<string>();
        var otherAttributes = change.Attributes
            .Where(a => a.NewValues.Count > 0
                && !string.Equals(a.Attribute, Attr.ObjectClass, StringComparison.OrdinalIgnoreCase)
                && !string.Equals(a.Attribute, dn.Leaf.Type, StringComparison.OrdinalIgnoreCase))
            .Select(a => Entry(sb, objectPlan, a.Attribute, a.NewValues, schema, secrets))
            .ToList();
        var command = new StringBuilder($"New-ADObject -Name {Quote(dn.Name)} -Type {Quote(type)} -Path {Quote(parent.ToString())}");
        if (otherAttributes.Count > 0)
        {
            command.Append(" -OtherAttributes @{").Append(string.Join("; ", otherAttributes)).Append('}');
        }

        Line(sb, command.Append(server).ToString());
        RemoveSecrets(sb, secrets);
    }

    /// <summary>The hashtable entry of an attribute; a secret attribute is read from the operator first (see <see cref="SecretEntry"/>).</summary>
    private static string Entry(StringBuilder sb, ObjectPlan objectPlan, string attribute, IReadOnlyList<string> values, ISchemaCatalog? schema, List<string> secrets) =>
        SecretAttributes.IsSecret(attribute, schema) ? SecretEntry(sb, objectPlan, attribute, values.Count, secrets) : HashEntry(attribute, values);

    /// <summary>
    /// Values of a secret attribute are never written to the script: each one is read with <c>Read-Host -AsSecureString</c>
    /// into a variable (added to <paramref name="secrets"/>) that the hashtable entry refers to.
    /// </summary>
    private static string SecretEntry(StringBuilder sb, ObjectPlan objectPlan, string attribute, int count, List<string> secrets)
    {
        var variables = new List<string>(count);
        for (var i = 0; i < count; i++)
        {
            var variable = string.Create(CultureInfo.InvariantCulture, $"secret{secrets.Count + 1}");
            secrets.Add(variable);
            var prompt = count == 1
                ? $"{attribute} for {objectPlan.DisplayName}"
                : string.Create(CultureInfo.InvariantCulture, $"{attribute} ({i + 1}/{count}) for {objectPlan.DisplayName}");
            Line(sb, $"${variable} = [System.Net.NetworkCredential]::new('', (Read-Host -AsSecureString -Prompt {Quote(prompt)})).Password");
            variables.Add("$" + variable);
        }

        var value = variables.Count == 1 ? variables[0] : $"@({string.Join(",", variables)})";
        return $"{Key(attribute)}={value}";
    }

    private static void RemoveSecrets(StringBuilder sb, List<string> secrets)
    {
        if (secrets.Count > 0)
        {
            Line(sb, $"Remove-Variable {string.Join(",", secrets)}");
        }
    }

    private static string HashEntry(string attribute, IReadOnlyList<string> values)
    {
        var literals = values.Select(v => Literal(attribute, v)).ToList();
        var value = literals.Count == 1 ? literals[0] : $"@({string.Join(",", literals)})";
        return $"{Key(attribute)}={value}";
    }

    private static string Literal(string attribute, string value)
    {
        // Binary values travel as hex in the plan (logonHours): written as a byte array.
        if (PipelineValues.IsHexEncoded(attribute) && PipelineValues.IsWireValue(attribute, value))
        {
            var bytes = (byte[])PipelineValues.ToWire(attribute, value);
            return $"[byte[]]({string.Join(",", bytes.Select(b => "0x" + b.ToString("x2", CultureInfo.InvariantCulture)))})";
        }

        if (NumericAttributes.Contains(attribute)
            && long.TryParse(value, NumberStyles.AllowLeadingSign, CultureInfo.InvariantCulture, out var number))
        {
            return number.ToString(CultureInfo.InvariantCulture);
        }

        return value switch
        {
            "TRUE" => "$true",
            "FALSE" => "$false",
            _ => Quote(value),
        };
    }

    /// <summary>Hashtable key / -Clear name: bare when it is a simple identifier, quoted otherwise (e.g. msDS-...).</summary>
    private static string Key(string attribute) => attribute.All(char.IsAsciiLetterOrDigit) ? attribute : Quote(attribute);

    /// <summary>Makes text safe for a single-line comment.</summary>
    private static string Comment(string text) => text.Replace('\r', ' ').Replace('\n', ' ');

    private static void Line(StringBuilder sb, string text = "") => sb.Append(text).Append(NewLine);
}
